-- Esquema de la tienda en linea para Oracle.
-- Tablas propias del caso de pedidos. No reutiliza las del foro ni las de la biblioteca.

CREATE SEQUENCE TIENDA_USUARIO_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE TIENDA_PRODUCTO_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE TIENDA_PEDIDO_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE TIENDA_DETALLE_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE TIENDA_USUARIOS (
    ID NUMBER(19) PRIMARY KEY,
    NOMBRE VARCHAR2(120) NOT NULL,
    CORREO VARCHAR2(150) NOT NULL,
    CLAVE VARCHAR2(100) NOT NULL,
    ROL VARCHAR2(20) NOT NULL,
    CONSTRAINT UK_TIENDA_USUARIO_CORREO UNIQUE (CORREO),
    CONSTRAINT CK_TIENDA_USUARIO_ROL CHECK (ROL IN ('CLIENTE', 'ADMINISTRADOR'))
);

CREATE TABLE TIENDA_PRODUCTOS (
    ID NUMBER(19) PRIMARY KEY,
    NOMBRE VARCHAR2(120) NOT NULL,
    DESCRIPCION VARCHAR2(500) NOT NULL,
    PRECIO NUMBER(12, 2) NOT NULL,
    STOCK NUMBER(10) NOT NULL,
    CONSTRAINT CK_TIENDA_PRODUCTO_PRECIO CHECK (PRECIO >= 0),
    CONSTRAINT CK_TIENDA_PRODUCTO_STOCK CHECK (STOCK >= 0)
);

CREATE TABLE TIENDA_PEDIDOS (
    ID NUMBER(19) PRIMARY KEY,
    FECHA_CREACION TIMESTAMP NOT NULL,
    CLIENTE_ID NUMBER(19) NOT NULL,
    TOTAL NUMBER(12, 2) NOT NULL,
    ESTADO_PAGO VARCHAR2(20) NOT NULL,
    PAGO_SIMULADO NUMBER(1) NOT NULL,
    MENSAJE VARCHAR2(200) NOT NULL,
    CONSTRAINT FK_TIENDA_PEDIDO_CLIENTE FOREIGN KEY (CLIENTE_ID) REFERENCES TIENDA_USUARIOS (ID),
    CONSTRAINT CK_TIENDA_PEDIDO_PAGO CHECK (ESTADO_PAGO IN ('PAGADO')),
    CONSTRAINT CK_TIENDA_PEDIDO_TOTAL CHECK (TOTAL >= 0)
);

CREATE TABLE TIENDA_DETALLE_PEDIDOS (
    ID NUMBER(19) PRIMARY KEY,
    PEDIDO_ID NUMBER(19) NOT NULL,
    PRODUCTO_ID NUMBER(19) NOT NULL,
    CANTIDAD NUMBER(10) NOT NULL,
    PRECIO_UNITARIO NUMBER(12, 2) NOT NULL,
    SUBTOTAL NUMBER(12, 2) NOT NULL,
    CONSTRAINT FK_TIENDA_DETALLE_PEDIDO FOREIGN KEY (PEDIDO_ID) REFERENCES TIENDA_PEDIDOS (ID),
    CONSTRAINT FK_TIENDA_DETALLE_PRODUCTO FOREIGN KEY (PRODUCTO_ID) REFERENCES TIENDA_PRODUCTOS (ID),
    CONSTRAINT CK_TIENDA_DETALLE_CANTIDAD CHECK (CANTIDAD >= 1)
);
